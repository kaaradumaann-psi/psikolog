def main() -> int:
    if not os.path.exists(CODE):
        print("Önce: npx tsx scripts/mmpi-audit/dump-keys.ts > .audit/code-keys.json", file=sys.stderr)
        return 1
    code = json.load(open(CODE, encoding="utf-8"))

    match = diff = missing = 0
    report: list[str] = []

    for name in sorted(SRC):
        s_dogru, s_yanlis, page, ver, note = SRC[name]
        c = code.get(name)
        if c is None:
            report.append(f"[MISSING] {name:10s} kodda yok (kaynak s.{page}, {len(s_dogru)+len(s_yanlis)} madde)")
            missing += 1
            continue
        c_dogru, c_yanlis = set(c["dogru"]), set(c["yanlis"])
        s_d, s_y = set(s_dogru), set(s_yanlis)

        only_src = (s_d | s_y) - (c_dogru | c_yanlis)      # kaynakta var, kodda yok
        only_code = (c_dogru | c_yanlis) - (s_d | s_y)     # kodda var, kaynakta yok
        flip = {x for x in (s_d & c_yanlis) | (s_y & c_dogru)}  # yön farkı

        if not only_src and not only_code and not flip:
            match += 1
            report.append(f"[MATCH  ] {name:10s} {len(s_d)+len(s_y):3d} madde  (kaynak s.{page}, dogrulama={ver})"
                          + (f"  NOT: {note}" if note else ""))
        else:
            diff += 1
            report.append(f"[DIFF   ] {name:10s} kaynak={len(s_d)+len(s_y):3d} kod={len(c_dogru)+len(c_yanlis):3d}"
                          f"  (kaynak s.{page}, dogrulama={ver})" + (f"  NOT: {note}" if note else ""))
            if flip:
                report.append(f"           YÖN FARKI (P0): {sorted(flip)}")
            if only_src:
                report.append(f"           kodda EKSİK : {sorted(only_src)}")
            if only_code:
                report.append(f"           kodda FAZLA : {sorted(only_code)}")

    print("=" * 78)
    print("Ek 9 (kitap s.244-256) ↔ kod anahtar karşılaştırması")
    print("=" * 78)
    for line in report:
        print(line)
    print("=" * 78)
    print(f"MATCH={match}  DIFF={diff}  MISSING={missing}  (toplam {len(SRC)} anahtar)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
